"""Write NtaLobbyLayout.swift from nta_room_lobby.py, so the game uses exactly the geometry the checks and sims passed.
Usage: python3 nta_gen_swift_layout.py <out dir>   (writes <out dir>/NtaLobbyLayout.swift)"""
import math, os, sys
import nl_kit as K
import nta_room_lobby as R

def f(v):
    return f"{v:.1f}"

def pt(p):
    return f"CGPoint(x: {f(p[0])}, y: {f(p[1])})"

def dedupe(seq):
    """Drop consecutive repeated points (a repeated point in an edge chain or loop makes a zero-length edge)."""
    out = []
    for p in seq:
        if not out or math.dist(p, out[-1]) > 0.05:
            out.append(p)
    return out

def pts(name, seq, doc, per_line=3):
    seq = dedupe(seq)
    out = [f"    /// {doc}", f"    static let {name}: [CGPoint] = ["]
    items = [pt(p) for p in seq]
    for i in range(0, len(items), per_line):
        out.append("        " + ", ".join(items[i:i + per_line]) + ",")
    out.append("    ]")
    return "\n".join(out)

P = R.room_parts()
left, right = R.stair_outline()
_, targets, desk = R.desk()
trig = (R.door_pt(R.DOOR_TRIGGER_T, "out", R.DOOR_HALF), R.door_pt(R.DOOR_TRIGGER_T, "in", R.DOOR_HALF))
blocks = [
    pts("stairsU", P["stairs U (floor-solid)"][1], "The stairs' floor-solid low end: a U whose back is a gable (16 pt peak), so a ball shot in while the stairs are shut rolls back out."),
    pts("stairsLeftRail", left, "The stairs ramp's left rail, mouth → top (drawn; the first 80 pt are the solid U)."),
    pts("stairsRightRail", right, "The stairs ramp's right rail, mouth → top (drawn)."),
    pts("doorBlock", P["door block"][1], "Everything left of the revolving-door lane, from the knee up to the arch (closed outline)."),
    pts("doorInnerWall", P["door inner wall"][1], "The lane's inner (playfield-side) wall: the end → the flare → the mouth post."),
    pts("doorRide", R.door_ride(), "From the lane's end onto the kit's left return wire, down to the left inlane (scripted ride)."),
    pts("deskBlock", desk, "The reception desk (closed outline): its front faces the left flipper, its top slopes down to the left."),
    pts("zombieWallBlock", R.zombie_wall_block(), "PAM's block on the right wall below the desk (closed): her face, then a roof sloping down to the left."),
]
zomb = []
for z in (R.ZOMBIE_DOOR, R.ZOMBIE_WALL):
    name, a, b, n, c = z
    zomb.append(f"        (name: \"{name}\", face: ({pt(a)}, {pt(b)}), normal: CGVector(dx: {n[0]:.4f}, dy: {n[1]:.4f}), center: {pt(c)}),")
tgt = []
for letter, fa, fb, c, n in targets:
    tgt.append(f"        (name: \"{letter}\", face: ({pt(fa)}, {pt(fb)}), normal: CGVector(dx: {n[0]:.4f}, dy: {n[1]:.4f}), center: {pt(c)}),")

swift = f'''//
//  NtaLobbyLayout.swift
//  9 to Alive (Table 10) — the LOBBY floor's geometry, on Neon Labyrinth's shared cell kit (NlCellLayout.swift).
//
//  GENERATED by tools/nta_gen_swift_layout.py from tools/nta_room_lobby.py (T10 M1 round 1 layout, approved by Aaron
//  2026-11-22; the zombies added in T10 M2 v2). Don't hand-edit: change the room's .py, re-run nta_lobby_checks.py / nta_lobby_fan.py / nta_lobby_sim.py,
//  regenerate. World points in the cell's coordinates, origin bottom-left.
//

import CoreGraphics

enum NtaLobbyLayout {{
    // MARK: STAIRS (the exit): a ramp up the middle to the top port
    static let stairsMouthY: CGFloat = {f(R.STAIR_MOUTH_Y)}
    static let stairsMouthPosts = [{pt((K.CX - R.STAIR_MOUTH_HALF, R.STAIR_MOUTH_Y))}, {pt((K.CX + R.STAIR_MOUTH_HALF, R.STAIR_MOUTH_Y))}]
    static let stairsPostRadius: CGFloat = {f(R.STAIR_POST_R)}
    static let stairsUTopY: CGFloat = {f(R.STAIR_U_TOP)}          // the stair door is drawn across here while shut
    static let stairsTopY: CGFloat = {f(R.STAIR_TOP_Y)}
    static let stairsChannelHalfWidth: CGFloat = {f(R.STAIR_CHANNEL_HALF)}
    /// Where the stairs ride ends: the top port (then out the top exit).
    static let stairsExit = {pt((K.CX, K.TOP_Y - 4))}
{chr(10).join(blocks[:3])}

    // MARK: REVOLVING DOOR (the exit puzzle): a spinner across a short lane up the left side
    static let doorAxis = CGVector(dx: {R.DOOR_U[0]:.4f}, dy: {R.DOOR_U[1]:.4f})   // up the lane (aimed along the right flipper's curved shot)
    static let doorMouthPost = {pt(R.door_pt(0.0, "in"))}
    static let doorPostRadius: CGFloat = {f(R.DOOR_POST_R)}
    /// The spinner's line across the lane (outer side → inner side).
    static let doorSpinner = ({pt(R.DOOR_SPINNER[0])}, {pt(R.DOOR_SPINNER[1])})
    /// Crossing this line going up the lane starts the ride onto the wire (20 pt before the lane's end).
    static let doorTrigger = ({pt(trig[0])}, {pt(trig[1])})
{chr(10).join(blocks[3:6])}

    // MARK: BARRICADE: the reception desk with targets B · A · R
{blocks[6]}
    static let deskTargets: [(name: String, face: (CGPoint, CGPoint), normal: CGVector, center: CGPoint)] = [
{chr(10).join(tgt)}
    ]

    // MARK: ZOMBIES (T10 M2 v2): standups where the Shot Lab found shots that hit nothing
{blocks[7]}
    /// GARY on the door block's underside (the right flipper's steep cross shot, ~111–116°), PAM on her block on the
    /// right wall below the desk (the left flipper's, ~61–64°). Each faces the flipper that makes the shot.
    static let zombies: [(name: String, face: (CGPoint, CGPoint), normal: CGVector, center: CGPoint)] = [
{chr(10).join(zomb)}
    ]
}}
'''
out = os.path.join(sys.argv[1] if len(sys.argv) > 1 else ".", "NtaLobbyLayout.swift")
open(out, "w").write(swift)
print("wrote", out)
