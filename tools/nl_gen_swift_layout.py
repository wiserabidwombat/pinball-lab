"""Write NlCellLayout.swift from nl_layout.py, so the game uses exactly the geometry the checks and sims passed.
Usage: python3 nl_gen_swift_layout.py out/NlCellLayout.swift"""
import math, sys
import nl_layout as L

def f(v):
    return f"{v:.1f}"

def pt(p):
    return f"CGPoint(x: {f(p[0])}, y: {f(p[1])})"

def pts(name, seq, doc, per_line=3):
    out = [f"    /// {doc}", f"    static let {name}: [CGPoint] = ["]
    items = [pt(p) for p in seq]
    for i in range(0, len(items), per_line):
        out.append("        " + ", ".join(items[i:i + per_line]) + ",")
    out.append("    ]")
    return "\n".join(out)

def standup(name, s, doc):
    fa, fb, ba, bb, n = s
    c = ((fa[0] + fb[0]) / 2, (fa[1] + fb[1]) / 2)
    return (f"    /// {doc}\n"
            f"    static let {name}Face: (CGPoint, CGPoint) = ({pt(fa)}, {pt(fb)})\n"
            f"    static let {name}Normal = CGVector(dx: {n[0]:.4f}, dy: {n[1]:.4f})\n"
            f"    static let {name}Center = {pt(c)}")

P = L.floor_parts()
left, right = L.ramp_outline()
blocks = []
for side in ("L", "R"):
    s = "Left" if side == "L" else "Right"
    blocks.append(pts(f"laneGuide{s}", P[f"lane guide {side}"][1], f"{s} lane guide: top post → straight → r {L.GUIDE_BEND_R:.0f} bend → slant to the pivot."))
    blocks.append(pts(f"outlaneWall{s}", P[f"outlane wall {side}"][1], f"{s} outlane channel wall, carried straight down from the bend."))
    blocks.append(pts(f"outlanePostRail{s}", P[f"outlane post rail {side}"][1], f"{s} outlane post rail (guide post → outlane post)."))
    blocks.append(pts(f"sling{s}", P[f"sling {side}"][1][:3], f"{s} sling: top, corner, tip (the kicking face is tip → top)."))
    blocks.append(pts(f"switchBlock{s}", P[f"switch block {side}"][1], f"{s} SWITCH target's block (closed outline)."))
    blocks.append(pts(f"returnWire{s}", L.return_wire(side), f"{s} return wire centreline (rail layer, scripted ride): top lane → arch → side wall → inlane."))
    blocks.append(pts(f"entryStub{s}", L.entry_stub(side), f"{s} entry portal → its return wire (join point last)."))
    tlx = L.TOP_PORT[0] if side == "L" else L.TOP_PORT[1]
    blocks.append(pts(f"topLaneWall{s}", P[f"top lane wall {side}"][1], f"{s} top lane wall."))
for key in ("W", "N", "E"):
    blocks.append(pts(f"rail{key}", L.rail_path(key), f"Light-rail {key} centreline (rail layer): ring → exit portal."))

swift = f'''//
//  NlCellLayout.swift
//  Neon Labyrinth (Table 08) — one cell's geometry: the shared cell kit + the Switchyard room.
//
//  GENERATED by tools/nl_gen_swift_layout.py from tools/nl_layout.py (T8 M1 v1 geometry). Don't hand-edit the
//  point lists: change nl_layout.py, re-run nl_checks.py / nl_sim.py, regenerate. World points, origin bottom-left.
//  Real ball scale and physics as CHOMP! (Table 07): ball r 15, flippers 80 (r 12 / 6), gravity −6.0, 51° stroke.
//

import CoreGraphics

enum NlCellLayout {{
    // MARK: world + physics (CHOMP!'s real-scale values)
    static let cellSize = CGSize(width: {L.CELL_W}, height: {L.CELL_H})
    static let centerX: CGFloat = {f(L.CX)}
    static let wallLeftX: CGFloat = {f(L.WALL_L)}
    static let wallRightX: CGFloat = {f(L.WALL_R)}
    static let archStartY: CGFloat = {f(L.ARCH_START)}
    static let topY: CGFloat = {f(L.TOP_Y)}
    static let gravity: CGFloat = -6.0
    static let ballRadius: CGFloat = {f(L.BALL_R)}
    static let closedMax: CGFloat = {f(L.CLOSED_MAX)}      // gaps the ball must never enter
    static let passageMin: CGFloat = {f(L.PASSAGE_MIN)}    // gaps the ball must use

    // MARK: kit — flippers
    static let flipperLength: CGFloat = {f(L.FLIP_LEN)}
    static let flipperPivotRadius: CGFloat = {f(L.FLIP_RP)}
    static let flipperTipRadius: CGFloat = {f(L.FLIP_RT)}
    static let flipperRestAngle: CGFloat = {L.FLIP_REST:.6f}     // 30° below horizontal
    static let flipperTravel: CGFloat = {L.FLIP_TRAVEL:.6f}        // 51° (stop 21° above)
    static let pivotLeft = {pt(L.PIVOT_L)}
    static let pivotRight = {pt(L.PIVOT_R)}

    // MARK: kit — walls (floor layer)
    /// Chute lip → slope under the left flipper → left wall (bulge 480–760) → arch → right wall → right slope → chute lip.
    static let outerWall: [CGPoint] = [
{chr(10).join("        " + ", ".join(pt(p) for p in L.outer_wall()[i:i + 3]) + "," for i in range(0, len(L.outer_wall()), 3))}
    ]
{chr(10).join(blocks)}
    static let guideBendLeft = {pt(L.GUIDE_BEND_L)}      // the theoretical corner (the guide itself curves, r {L.GUIDE_BEND_R:.0f})
    static let laneGuidePostLeft = {pt((L.GUIDE_X, L.GUIDE_TOP_Y))}
    static let laneGuidePostRight = {pt(L.M((L.GUIDE_X, L.GUIDE_TOP_Y)))}
    static let outlanePostLeft = {pt(L.OUTLANE_POST_L)}
    static let outlanePostRight = {pt(L.M(L.OUTLANE_POST_L))}
    static let laneGuidePostRadius: CGFloat = {f(L.GUIDE_POST_R)}
    static let slingTopPostRadius: CGFloat = {f(L.SLING_POST_TOP)}
    static let slingTipPostRadius: CGFloat = {f(L.SLING_POST_TIP)}
    static let slingCornerPostRadius: CGFloat = {f(L.SLING_POST_CORNER)}
    static let topLanePostRadius: CGFloat = {f(L.TOP_LANE_POST_R)}
    static let topLaneBottomY: CGFloat = {f(L.TOP_LANE_BOTTOM)}
    static let topLanePosts = [{pt((L.TOP_PORT[0], L.TOP_LANE_BOTTOM))}, {pt((L.TOP_PORT[1], L.TOP_LANE_BOTTOM))}]
    static let rampMouthPosts = [{pt((L.CX - L.RAMP_MOUTH_HALF, L.RAMP_MOUTH_Y))}, {pt((L.CX + L.RAMP_MOUTH_HALF, L.RAMP_MOUTH_Y))}]

    // MARK: kit — arrivals, exits, drain
    static let drainLineY: CGFloat = {f(L.DRAIN_LINE_Y)}        // crossed going down → the cell below (bottom row: ball lost)
    static let entryPortalY: ClosedRange<CGFloat> = {f(L.ENTRY_PORTAL[0])}...{f(L.ENTRY_PORTAL[1])}
    static let sideExitY: ClosedRange<CGFloat> = {f(L.SIDE_EXIT[0])}...{f(L.SIDE_EXIT[1])}
    static let topPortX: ClosedRange<CGFloat> = {f(L.TOP_PORT[0])}...{f(L.TOP_PORT[1])}
    static let wireReleaseSpeed: CGFloat = {f(L.WIRE_RELEASE_SPEED)}   // return wires release straight down in the inlane
    /// From below: a scripted rise up the chute (collisions off) to here, then the pop onto a flipper (sides alternate).
    static let upRelease = {pt(L.UP_RELEASE)}
    static let upPopLeft = CGVector(dx: {f(L.UP_POP["L"][0])}, dy: {f(L.UP_POP["L"][1])})
    static let upPopRight = CGVector(dx: {f(L.UP_POP["R"][0])}, dy: {f(L.UP_POP["R"][1])})
    static let upRiseStartY: CGFloat = {f(L.DRAIN_LINE_Y)}

    // MARK: Switchyard
    static let hubCenter = {pt(L.HUB)}
    static let hubTrackRadius: CGFloat = {f(L.HUB_TRACK_R)}
    static let hubBaseRadius: CGFloat = {f(L.HUB_BASE_R)}       // floor-solid base under the turntable
    static let railRingRadii: (CGFloat, CGFloat) = ({f(L.RAIL_RING_R[0])}, {f(L.RAIL_RING_R[1])})
    static let railHalfWidth: CGFloat = {f(L.RAIL_HALF)}
    static let rampMouthY: CGFloat = {f(L.RAMP_MOUTH_Y)}
    static let rampTopY: CGFloat = {f(L.RAMP_TOP_Y)}
    static let rampUTopY: CGFloat = {f(L.RAMP_U_TOP)}
    static let rampMouthPostRadius: CGFloat = {f(L.RAMP_POST_R)}
{pts("rampLeftRail", left, "Ramp left rail, mouth → turntable (the first 80 pt are floor-solid).")}
{pts("rampRightRail", right, "Ramp right rail, mouth → turntable.")}
{pts("rampU", P["ramp U (floor-solid)"][1], "The ramp's floor-solid low end: left side, gabled back, right side.")}
{pts("railsBlock", P["RAILS block"][1] + [P["RAILS block"][1][0]], "RAILS target's block on the right wall (closed outline: last = first).")}
{standup("switchLeft", L.SWITCH_L, "SWITCH < (turns the turntable anticlockwise), faces the right flipper.")}
{standup("switchRight", L.SWITCH_R, "SWITCH > (turns it clockwise), faces the left flipper.")}
{standup("rails", L.RAILS, "RAILS (steps the light-rail ring's bridge), faces the left flipper.")}
}}
'''
open(sys.argv[1], "w").write(swift)
print("wrote", sys.argv[1], len(swift.splitlines()), "lines")
