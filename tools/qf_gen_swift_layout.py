"""Writes QfForestLayout.swift (Quest & Flipper, Table 09: the Haunted Forest's geometry) from qf_layout.py.
Usage: python3 tools/qf_gen_swift_layout.py <path>/QfForestLayout.swift
Change qf_layout.py, re-run qf_checks.py / qf_sim.py, then regenerate. Don't hand-edit the Swift file."""
import math, sys
import qf_layout as L

def f(v):
    return f"{v:.2f}"

def pt(p):
    return f"CGPoint(x: {f(p[0])}, y: {f(p[1])})"

def pts(ps, indent="        "):
    rows, line = [], []
    for p in ps:
        line.append(pt(p))
        if len(line) == 3:
            rows.append(", ".join(line)); line = []
    if line:
        rows.append(", ".join(line))
    return "[\n" + ",\n".join(indent + r for r in rows) + ",\n    ]"

def closed(ps):
    ps = list(ps)
    return ps if ps[0] == ps[-1] else ps + [ps[0]]

P = L.floor_parts(mode_parts=False)
gl = P["lane guide L"][1]; gr = P["lane guide R"][1]
rp = L.ramp_path()
lr, rr = rp.rails(L.RAMP_CHANNEL_HALF)
fa, fb, _, _, ln = L.LANTERN_E
u_top = L.RAMP_MOUTH_Y + L.RAMP_U_LEN
bark = [(x, L.BARK_Y + L.BARK_DEPTH / 2) for x in L.BARK_XS]
orbit_line = ((L.ARCH_MID_X + 150, 1180.0), (L.ARCH_MID_X + 150, L.TOP_Y + 5))
spinner = ((L.WALL_L, L.SPINNER_Y), (L.ORBIT_INNER_X, L.SPINNER_Y))
ramp_entry_y = L.RAMP_MOUTH_Y + 12

